-- 1. Create Quotes / Leads Table
CREATE TABLE IF NOT EXISTS public.quotes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  full_name TEXT NOT NULL,
  phone_number TEXT NOT NULL,
  email_address TEXT,
  service_required TEXT NOT NULL,
  suburb_postcode TEXT,
  project_description TEXT,
  status TEXT DEFAULT 'New'
);

-- 2. Enable Row Level Security
ALTER TABLE public.quotes ENABLE ROW LEVEL SECURITY;

-- 3. Policy: Allow visitors to submit quote enquiries (INSERT)
CREATE POLICY "Allow public to insert quotes" ON public.quotes
  FOR INSERT
  TO anon, authenticated
  WITH CHECK (true);

-- 4. Policy: Allow reading quotes (SELECT)
CREATE POLICY "Allow reading quotes" ON public.quotes
  FOR SELECT
  TO anon, authenticated
  USING (true);

-- 5. Policy: Allow updating quote status (UPDATE)
CREATE POLICY "Allow updating quotes" ON public.quotes
  FOR UPDATE
  TO anon, authenticated
  USING (true);

-- 6. Policy: Allow deleting quotes (DELETE)
CREATE POLICY "Allow deleting quotes" ON public.quotes
  FOR DELETE
  TO anon, authenticated
  USING (true);
